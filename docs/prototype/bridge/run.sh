#!/usr/bin/env bash
# Prototype of the gtr -> go bridge: a project without a hand-written go.mod, packages in gtr_modules/
set -u
ROOT=${KEEP:-$(mktemp -d)}; mkdir -p "$ROOT"; cd "$ROOT"
mk(){ mkdir -p "$(dirname "$1")"; cat > "$1"; }

# --- packages in gtr_modules (what gtr extracted from the store) ---
mk gtr_modules/orm/gtr.json <<'J'
{"name":"orm","version":"0.1.0"}
J
mk gtr_modules/orm/orm.go <<'G'
package orm
type Driver interface{ Name() string }
func Open(d Driver) string { return "orm:" + d.Name() }
G
mk gtr_modules/orm/schema/schema.go <<'G'
package schema
func Table(n string) string { return "table " + n }
G
mk gtr_modules/orm-mysql/gtr.json <<'J'
{"name":"orm-mysql","version":"0.1.0","dependencies":{"orm":"^0.1","go:github.com/go-sql-driver/mysql":"^1.10"}}
J
mk gtr_modules/orm-mysql/mysql.go <<'G'
package mysql
import ("orm"; drv "github.com/go-sql-driver/mysql")
type d struct{}
func (d) Name() string { return "mysql/" + drv.Version }
func Driver() orm.Driver { return d{} }
G
# an external Go module that gtr downloaded from proxy.golang.org into the store (faked here)
mk gtr_modules/.go/github.com/go-sql-driver/mysql@v1.10.0/go.mod <<'G'
module github.com/go-sql-driver/mysql
go 1.21
G
mk gtr_modules/.go/github.com/go-sql-driver/mysql@v1.10.0/mysql.go <<'G'
package mysql
const Version = "1.10.0"
G

# --- project code ---
mk gtr.json <<'J'
{"name":"app","version":"1.0.0","engines":{"go":">=1.22"},"dependencies":{"orm":"^0.1","orm-mysql":"^0.1"}}
J
mk main.go <<'G'
package main
import ("fmt"; "orm"; "orm/schema"; mysql "orm-mysql")
func main(){ fmt.Println(orm.Open(mysql.Driver()), schema.Table("users")) }
G
mk main_test.go <<'G'
package main
import ("testing"; "orm"; "orm-mysql")
func TestOpen(t *testing.T){ if got := orm.Open(mysql.Driver()); got != "orm:mysql/1.10.0" { t.Fatal(got) } }
G

echo "=== 1. NO go.mod in packages: replace to a directory without go.mod"
mk go.mod <<'G'
// generated by gtr from gtr.json — edit gtr.json or run `gtr sync`
// gtr:hash PLACEHOLDER
module app
go 1.22
require (
	orm v0.1.0
	orm-mysql v0.1.0
	github.com/go-sql-driver/mysql v1.10.0
)
replace (
	orm => ./gtr_modules/orm
	orm-mysql => ./gtr_modules/orm-mysql
	github.com/go-sql-driver/mysql => ./gtr_modules/.go/github.com/go-sql-driver/mysql@v1.10.0
)
G
export GOPROXY=off GOFLAGS=-mod=mod GONOSUMDB=* GOFLAGS=-mod=mod GOWORK=off
go build -o app . 2>&1 | head -5

echo "=== 2. gtr also generates a go.mod in every package"
mk gtr_modules/orm/go.mod <<'G'
// generated by gtr
module orm
go 1.22
G
mk gtr_modules/orm-mysql/go.mod <<'G'
// generated by gtr
module orm-mysql
go 1.22
require (
	orm v0.1.0
	github.com/go-sql-driver/mysql v1.10.0
)
G
go build -o app . && ./app
echo "--- go test";  go test ./... 2>&1
echo "--- go vet";   go vet ./... && echo vet ok
echo "--- go list (what gopls uses)"; go list -deps -f '{{if .Module}}{{.ImportPath}} <- {{.Module.Path}}@{{.Module.Version}} {{.Module.Dir}}{{end}}' . | grep -v '^app'
echo "--- versions in the binary"; go version -m app | grep -E 'dep|=>'
echo "--- was go.sum created?"; ls go.sum 2>&1
echo "--- does go mod tidy touch go.mod?"; cp go.mod /tmp/gm.bak; go mod tidy 2>&1 | head -3; diff /tmp/gm.bak go.mod && echo "tidy: no changes"

echo "=== 3. stdlib collision: a package named errors"
mkdir -p gtr_modules/errors && printf 'package errors\nfunc Mine() string { return "mine" }\n' > gtr_modules/errors/e.go && printf 'module errors\ngo 1.22\n' > gtr_modules/errors/go.mod
cp go.mod go.mod.ok
printf 'require errors v0.1.0\nreplace errors => ./gtr_modules/errors\n' >> go.mod
mkdir -p cmd/x && printf 'package main\nimport "errors"\nfunc main(){ println(errors.Mine()) }\n' > cmd/x/main.go
go build ./cmd/x 2>&1 | head -3
rm -rf cmd/x; cp go.mod.ok go.mod

echo "=== 4. a dotless name of a future stdlib-like package, e.g. 'log2', is ok; 'internal' in the path?"
echo "=== 5. missing replace -> what the user sees"
sed -i '/orm-mysql =>/d' go.mod; go build . 2>&1 | head -3
