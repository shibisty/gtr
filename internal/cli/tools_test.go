func TestGlobalFlags(t *testing.T) {
	h := newHarness(t)
	h.installGo("1.25.0", "1.26.9")
	h.installManager("0.1.0", "0.2.0")
	h.project(`{"name":"app","engines":{"go":">=1.25"}}`)
	for _, tc := range []struct {
		args    []string
		goV     string
		manager string
	}{
		{[]string{"run", "x"}, "1.26.9", "0.2.0"},
		{[]string{"--go", "1.25", "run", "x"}, "1.25.0", "0.2.0"},
		{[]string{"--go=~1.25", "--gtr", "0.1", "run", "x"}, "1.25.0", "0.1.0"},
	} {
		h.calls = nil
		if err := h.run(tc.args...); err != nil {
			t.Fatalf("%v: %v", tc.args, err)
		}
		c := h.calls[0]
		if c.env["GTR_GO_VERSION"] != tc.goV || !strings.Contains(c.bin, filepath.Join("gtr", tc.manager)) || strings.Join(c.args, " ") != "run x" {
			t.Fatalf("%v: go %s, manager %s, args %v", tc.args, c.env["GTR_GO_VERSION"], c.bin, c.args)
		}
	}
	// The override applies to self commands too.
	h.out.Reset()
	if err := h.run("--go", "1.25", "self", "current"); err != nil || !strings.Contains(h.stdout(), "1.25.0") {
		t.Fatalf("self current: %v %s", err, h.stdout())
	}
	for _, args := range [][]string{{"--go"}, {"--go", "-x"}, {"--go", "nope", "run"}, {"--gtr="}} {
		if err := newHarness(t).run(args...); !errors.Is(err, ErrUsage) {
			t.Errorf("%v: want a usage error, got %v", args, err)
		}
	}
}

func envMap(t *testing.T, out string) map[string]string {
	t.Helper()
	m := map[string]string{}
	for _, line := range strings.Split(strings.TrimSpace(out), "\n") {
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			t.Fatalf("bad line %q", line)
		}
		m[k] = strings.Trim(v, "'")
	}
	return m
}

func TestEnv(t *testing.T) {
	h := newHarness(t)
	h.env["HOME"] = "/home/x"
	h.installGo("1.26.9")
	h.installManager("0.2.0")
	h.project(`{"name":"app","engines":{"go":"^1.26"}}`)
	if err := h.run("env"); err != nil {
		t.Fatal(err)
	}
	m := envMap(t, h.stdout())
	want := map[string]string{
		"GTR_VERSION": "0.1.0", "GTR_HOME": h.root, "GTR_PROJECT": h.cwd, "GTR_GO_VERSION": "1.26.9",
		"GOROOT": filepath.Join(h.root, "go", "1.26.9"), "GOPATH": filepath.Join("/home/x", "go"),
		"GTR_MANAGER_VERSION": "0.2.0", "GTR_MANAGER": filepath.Join(h.root, "gtr", "0.2.0", "gtr-manager"), "GTR_GO_MODE": "",
	}
	for k, v := range want {
		if m[k] != v {
			t.Errorf("%s = %q, want %q", k, m[k], v)
		}
	}
	if _, ok := m["GOPROXY"]; ok {
		t.Error("GOPROXY printed outside a generated project")
	}

	// A generated go.mod: the go command's environment is shown too.
	os.WriteFile(filepath.Join(h.cwd, "go.mod"), []byte(generatedGoMod), 0o644)
	h.sout.Reset()
	if err := h.run("env"); err != nil {
		t.Fatal(err)
	}
	m = envMap(t, h.stdout())
	if m["GTR_GO_MODE"] != "project" || m["GOPROXY"] != "off" || m["GOWORK"] != "off" || !strings.Contains(m["GOFLAGS"], "-mod=mod") {
		t.Fatalf("project mode: %v", m)
	}

	// Values only, and JSON.
	h.sout.Reset()
	if err := h.run("env", "GTR_GO_VERSION", "GTR_GO_MODE"); err != nil || h.stdout() != "1.26.9\nproject\n" {
		t.Fatalf("names: %v %q", err, h.stdout())
	}
	h.sout.Reset()
	var obj map[string]string
	if err := h.run("env", "--json"); err != nil || json.Unmarshal([]byte(h.stdout()), &obj) != nil || obj["GTR_GO_VERSION"] != "1.26.9" {
		t.Fatalf("json: %v %s", err, h.stdout())
	}
	if err := h.run("env", "-x"); !errors.Is(err, ErrUsage) {
		t.Fatalf("bad flag: %v", err)
	}
}

