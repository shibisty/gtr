// doctorHarness has reachable fake servers for all network checks.
func doctorHarness(t *testing.T) *harness {
	h := newHarness(t)
	proxy := httptest.NewServer(http.NotFoundHandler()) // any response means reachable
	t.Cleanup(proxy.Close)
	h.env["GTR_GOPROXY"] = proxy.URL
	h.env["GITHUB_TOKEN"] = "t"
	return h
}

